use std::path::{Path, PathBuf};
use std::sync::Arc;

use crate::error::Result;

use super::project_activity::assess;
use super::{dev_search_roots, execute_per_item, is_idle, CleanProvider};
use crate::clean::fs_safe::{dir_size_checked, walk_with};
use crate::clean::scan_context::ScanContext;
use crate::clean::types::{CleanItem, ExecAction, ExecReport, RiskLevel};
use crate::runner::{CommandRunner, RealRunner};

const ID: &str = "node-modules";
const LABEL: &str = "node_modules (idle)";

pub struct NodeModules {
    pub idle_days: u64,
    pub search_roots: Vec<PathBuf>,
    runner: Arc<dyn CommandRunner>,
}

impl NodeModules {
    pub fn new(idle_days: u64) -> Self {
        Self::with_runner(idle_days, Arc::new(RealRunner))
    }

    pub fn with_runner(idle_days: u64, runner: Arc<dyn CommandRunner>) -> Self {
        Self {
            idle_days,
            search_roots: dev_search_roots(),
            runner,
        }
    }
}

impl CleanProvider for NodeModules {
    fn id(&self) -> &'static str {
        ID
    }
    fn label(&self) -> &'static str {
        LABEL
    }
    fn inclusion_reason(&self) -> String {
        format!(
            "node_modules in projects with no edits, commits or uncommitted changes for {} days; reinstall restores them",
            self.idle_days
        )
    }
    fn risk(&self) -> RiskLevel {
        RiskLevel::Review
    }
    fn desktop_trash_paths(&self) -> bool {
        true
    }
    fn available(&self) -> bool {
        !self.search_roots.is_empty()
    }
    fn discover(&self, ctx: &ScanContext<'_>) -> Result<Vec<CleanItem>> {
        let mut items = Vec::new();
        for root in &self.search_roots {
            for found in find_node_modules(ctx, root, self.idle_days) {
                if ctx.is_cancelled() {
                    return Ok(Vec::new());
                }
                let manifest = found.with_file_name("package.json");
                let Some(evidence) = assess(&*self.runner, &manifest, self.idle_days, ctx)? else {
                    continue;
                };
                let size = dir_size_checked(&found, ctx);
                items.push(CleanItem {
                    category_id: ID.to_string(),
                    category_label: LABEL.to_string(),
                    path: found,
                    size,
                    risk: RiskLevel::Review,
                    evidence,
                });
            }
        }
        Ok(items)
    }
    fn execute(&self, items: &[CleanItem], action: ExecAction) -> Result<ExecReport> {
        execute_per_item(items, action, ID)
    }
}

/// Walks `root` symlink-safe and returns every `node_modules` dir whose
/// parent has a `package.json` modified more than `idle_days` days ago.
/// Does NOT descend into a `node_modules` dir once found.
pub fn find_node_modules(ctx: &ScanContext<'_>, root: &Path, idle_days: u64) -> Vec<PathBuf> {
    let mut found: Vec<PathBuf> = Vec::new();
    walk_with(root, ctx, |path, meta| {
        if !meta.file_type().is_dir() {
            return false;
        }
        let is_node_modules = path.file_name().and_then(|n| n.to_str()) == Some("node_modules");
        if is_node_modules {
            if is_idle_node_modules(path, idle_days) {
                found.push(path.to_path_buf());
            }
            // Never recurse into node_modules itself (avoid nested transitive dirs).
            return false;
        }
        true
    });
    found
}

/// True iff `nm` is `<parent>/node_modules` and `<parent>/package.json`
/// exists and is idle.
pub fn is_idle_node_modules(nm: &Path, idle_days: u64) -> bool {
    let parent = match nm.parent() {
        Some(p) => p,
        None => return false,
    };
    let manifest = parent.join("package.json");
    if !manifest.is_file() {
        return false;
    }
    is_idle(&manifest, idle_days)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::clean::providers::known_category_ids;
    use std::fs;

    fn tempdir(label: &str) -> PathBuf {
        let mut base = std::env::temp_dir();
        base.push(format!(
            "tiny-clean-nm-{}-{}",
            label,
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        fs::create_dir_all(&base).unwrap();
        base
    }

    #[test]
    fn node_modules_id_in_known_categories() {
        assert!(known_category_ids().contains(&ID));
    }

    #[test]
    fn refuses_node_modules_without_package_json() {
        let root = tempdir("orphan");
        let proj = root.join("ghost");
        fs::create_dir_all(proj.join("node_modules")).unwrap();
        // No package.json → must not be flagged.
        let found = find_node_modules(&ScanContext::unchecked(), &root, 0);
        assert!(found.is_empty(), "got: {:?}", found);
        let _ = crate::clean::fs_safe::remove_recursive_safe(&root);
    }

    #[test]
    fn idle_threshold_filters_recently_modified() {
        let root = tempdir("idle");
        let proj = root.join("alive");
        fs::create_dir_all(proj.join("node_modules")).unwrap();
        let manifest = proj.join("package.json");
        fs::write(&manifest, b"{}").unwrap();
        // Just-touched manifest with idle_days=30 → must NOT be flagged.
        let found = find_node_modules(&ScanContext::unchecked(), &root, 30);
        assert!(found.is_empty(), "fresh package.json should not flag");
        // Backdate manifest 31 days → idle_days=30 must now flag it.
        let old = std::time::SystemTime::now() - std::time::Duration::from_secs(31 * 86_400);
        std::fs::File::open(&manifest)
            .unwrap()
            .set_modified(old)
            .unwrap();
        let found_old = find_node_modules(&ScanContext::unchecked(), &root, 30);
        assert_eq!(found_old.len(), 1, "31-day-old manifest should flag");
        let _ = crate::clean::fs_safe::remove_recursive_safe(&root);
    }

    #[test]
    fn does_not_descend_into_node_modules() {
        // Nested node_modules/foo/node_modules must not produce 2 entries.
        let root = tempdir("nested");
        let proj = root.join("p");
        let nm = proj.join("node_modules");
        let inner = nm.join("foo").join("node_modules");
        fs::create_dir_all(&inner).unwrap();
        let manifest = proj.join("package.json");
        fs::write(&manifest, b"{}").unwrap();
        let old = std::time::SystemTime::now() - std::time::Duration::from_secs(40 * 86_400);
        std::fs::File::open(&manifest)
            .unwrap()
            .set_modified(old)
            .unwrap();
        let found = find_node_modules(&ScanContext::unchecked(), &root, 30);
        assert_eq!(found.len(), 1);
        assert_eq!(found[0], nm);
        let _ = crate::clean::fs_safe::remove_recursive_safe(&root);
    }

    use crate::clean::types::Evidence;
    use crate::runner::test_support::MockRunner;

    fn provider(root: &Path, runner: MockRunner) -> NodeModules {
        let mut p = NodeModules::with_runner(30, Arc::new(runner));
        p.search_roots = vec![root.to_path_buf()];
        p
    }

    #[test]
    fn discover_skips_project_when_git_cannot_answer() {
        let root = tempdir("discover-git");
        fs::create_dir_all(root.join(".git")).unwrap();
        let proj = root.join("p");
        fs::create_dir_all(proj.join("node_modules")).unwrap();
        let manifest = proj.join("package.json");
        fs::write(&manifest, b"{}").unwrap();
        let old = std::time::SystemTime::now() - std::time::Duration::from_secs(90 * 86_400);
        std::fs::File::open(&manifest)
            .unwrap()
            .set_modified(old)
            .unwrap();
        let log = format!(
            "--no-optional-locks -C {} log -1 --format=%ct -- .",
            proj.display()
        );
        let runner = MockRunner::new().with_exit(
            "/usr/bin/git",
            &log.split(' ').collect::<Vec<_>>(),
            128,
            "",
        );
        let items = provider(&root, runner)
            .discover(&ScanContext::unchecked())
            .unwrap();
        assert!(items.is_empty());
        let _ = crate::clean::fs_safe::remove_recursive_safe(&root);
    }

    #[test]
    fn discover_offers_idle_project_outside_git_with_evidence() {
        let root = tempdir("discover-nogit");
        let proj = root.join("p");
        fs::create_dir_all(proj.join("node_modules")).unwrap();
        let manifest = proj.join("package.json");
        fs::write(&manifest, b"{}").unwrap();
        let old = std::time::SystemTime::now() - std::time::Duration::from_secs(90 * 86_400);
        std::fs::File::open(&manifest)
            .unwrap()
            .set_modified(old)
            .unwrap();
        let items = provider(&root, MockRunner::new())
            .discover(&ScanContext::unchecked())
            .unwrap();
        assert_eq!(items.len(), 1);
        assert_eq!(items[0].evidence.last(), Some(&Evidence::NotGitRepo));
        let _ = crate::clean::fs_safe::remove_recursive_safe(&root);
    }
}
