    #[test]
    fn desktop_lists_every_project_and_none_outside_git_is_safe() {
        let root = tempdir("desktop");
        let old = project(&root, "old", 40);
        let idle = project(&root, "idle", 8);
        let active = project(&root, "active", 2);
        let desktop = desktop(&root, MockRunner::new());
        assert_eq!(desktop.label(), "node_modules");
        assert!(desktop.inclusion_reason().contains("7 days"));
        let items = desktop.discover(&ScanContext::unchecked()).unwrap();
        let risk = |path: &Path| items.iter().find(|i| i.path == path).map(|i| i.risk);
        // Outside git a manifest's age alone never makes a project Safe.
        assert_eq!(risk(&old), Some(RiskLevel::Review));
        assert_eq!(risk(&idle), Some(RiskLevel::Review));
        assert_eq!(risk(&active), Some(RiskLevel::Review));
        let old_item = items.iter().find(|i| i.path == old).unwrap();
        assert_eq!(old_item.evidence.last(), Some(&Evidence::NotGitRepo));
        // The CLI's scope on the same fixture: idle for 30 days, Review.
        let cli = provider(&root, MockRunner::new())
            .discover(&ScanContext::unchecked())
            .unwrap();
        let listed: Vec<_> = cli.iter().map(|i| (&i.path, i.risk)).collect();
        assert_eq!(listed, vec![(&old, RiskLevel::Review)]);
        assert_eq!(cli[0].category_label, LABEL);
        let _ = crate::clean::fs_safe::remove_recursive_safe(&root);
    }

    #[test]
    fn node_modules_with_tracked_files_is_never_offered_nor_acted_on() {
        let root = tempdir("tracked");
        fs::create_dir_all(root.join(".git")).unwrap();
        let committed = project(&root, "committed", 40);
        let proj = committed.parent().unwrap();
        let old = std::time::SystemTime::now() - std::time::Duration::from_secs(40 * 86_400);
        let ct = old.duration_since(std::time::UNIX_EPOCH).unwrap().as_secs();
        let log = git(proj, &["log", "-1", "--format=%ct", "--", "."]);
        let status = git(proj, &STATUS);
        let ls = git(&committed, &["ls-files", "--", "."]);
        let runner = || {
            no_filters(MockRunner::new(), proj)
                .with_exit("/usr/bin/git", &strs(&log), 0, &format!("{ct}\n"))
                .with_exit("/usr/bin/git", &strs(&status), 0, "")
                .with_exit("/usr/bin/git", &strs(&ls), 0, "left-pad/index.js\n")
        };
        let ctx = ScanContext::unchecked();
        assert!(desktop(&root, runner()).discover(&ctx).unwrap().is_empty());
        assert!(provider(&root, runner()).discover(&ctx).unwrap().is_empty());
        // Tracked after discovery: the guard refuses it right before acting.
        assert!(provider(&root, runner()).check_item(&committed).is_err());
        let _ = crate::clean::fs_safe::remove_recursive_safe(&root);
    }

    /// Five projects of different sizes; the third has a subfolder that
    /// cannot be read. Returns the `node_modules` folders in walk order.
    fn sized_projects(root: &Path) -> Vec<PathBuf> {
        let folders: Vec<_> = (0..5)
            .map(|n| project(root, &format!("p{n}"), 40))
            .collect();
        for (n, nm) in folders.iter().enumerate() {
            let pkg = nm.join("pkg");
            fs::create_dir_all(&pkg).unwrap();
            for f in 0..=n {
                fs::write(pkg.join(format!("f{f}")), vec![7u8; 5000 * (f + 1)]).unwrap();
            }
        }
        let locked = folders[2].join("locked");
        fs::create_dir_all(&locked).unwrap();
        fs::write(locked.join("hidden"), b"x").unwrap();
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&locked, fs::Permissions::from_mode(0o000)).unwrap();
        folders
    }

    fn unlock(folders: &[PathBuf]) {
        use std::os::unix::fs::PermissionsExt;
        let locked = folders[2].join("locked");
        fs::set_permissions(locked, fs::Permissions::from_mode(0o755)).unwrap();
    }

    #[test]
    fn parallel_sizing_matches_serial_sizes_and_findings() {
        let root = tempdir("parallel");
        let folders = sized_projects(&root);
        let mut expected = Vec::new();
        let serial = ScanContext::unchecked();
        for path in find_node_modules(&serial, &root, Some(30)) {
            let size = dir_size_checked(&path, &serial);
            expected.push((path, size));
        }
        let parallel = ScanContext::unchecked();
        let items = provider(&root, MockRunner::new())
            .discover(&parallel)
            .unwrap();
        let (serial_findings, parallel_findings) =
            (serial.take_findings(), parallel.take_findings());
        unlock(&folders);
        let got: Vec<_> = items.iter().map(|i| (i.path.clone(), i.size)).collect();
        assert_eq!(got, expected);
        assert_eq!(got.len(), 5);
        assert!(got.iter().all(|(_, size)| *size > 0));
        assert_eq!(parallel_findings, serial_findings);
        let unreadable = &parallel_findings.unreadable;
        assert_eq!(unreadable.keys().collect::<Vec<_>>(), vec![&folders[2]]);
        let _ = crate::clean::fs_safe::remove_recursive_safe(&root);
    }

    #[test]
    fn size_all_keeps_order_and_merges_each_folders_findings() {
        let root = tempdir("size-all");
        let folders = sized_projects(&root);
        let paths: Vec<&Path> = folders.iter().map(PathBuf::as_path).collect();
        let ctx = ScanContext::unchecked();
        let sizes = size_all(&paths, &ctx);
        let findings = ctx.take_findings();
        let reference = ScanContext::unchecked();
        let expected: Vec<u64> = paths
            .iter()
            .map(|p| dir_size_checked(p, &reference))
            .collect();
        let expected_findings = reference.take_findings();
        unlock(&folders);
        assert_eq!(sizes, expected);
        assert_eq!(findings, expected_findings);
        assert_eq!(findings.unreadable[&folders[2]].entries, 1);
        let _ = crate::clean::fs_safe::remove_recursive_safe(&root);
    }

